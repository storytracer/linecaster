def test_the_evidence_format_stays_for_derivatives():
    """An evaluation's evidence records validate with ``Evidence`` (``linecaster.evidence/1``): one preset or recipe
    each (``id@edition`` in records from before 0.10). The catalog reads none."""
    from pydantic import ValidationError

    ev = Evidence.model_validate({"schema": "linecaster.evidence/1", "recipe": "r@1", "source": "own-run",
                                  "dataset": "d@r", "metrics": {"lines_identical": 10}, "date": dt.date(2026, 11, 3)})
    assert ev.subject == "r@1" and not ev.preset
    with pytest.raises(ValidationError, match="one preset or one recipe"):
        Evidence.model_validate({"schema": "linecaster.evidence/1", "recipe": "r@1", "preset": "p@1",
                                 "source": "own-run", "dataset": "d", "metrics": {}, "date": dt.date(2026, 11, 3)})
    assert "evidence" not in {f.name for f in fields(Directory)}


def test_a_recipe_fills_a_pipeline(tmp_path):
    import argparse

    from linecaster.execution import run

    make(tmp_path)
    make_recipe(tmp_path)
    ap = argparse.ArgumentParser()
    ap.add_argument("--recipe")
    ap.add_argument("--recognition")
    ap.add_argument("--window", type=int, default=48)
    c = Catalog([tmp_path])
    argv = ["--recipe", "r"]
    a = ap.parse_args(argv)
    run.apply_recipe(ap, a, "transcribe_vlm.v1", {"recognition": "recognition"}, argv, c)
    assert (a.recognition, a.window) == ("p", 16)
    assert a.recipe_record == {"ref": "r", "pipeline": "transcribe_vlm.v1", "sha256": c.resolve_recipe("r").sha256}
    argv += ["--window", "8", "--recognition", "other"]
    a = ap.parse_args(argv)
    run.apply_recipe(ap, a, "transcribe_vlm.v1", {"recognition": "recognition"}, argv, c)
    assert a.recipe_record["overrides"] == {"recognition": "other", "window": 8}
    with pytest.raises(PipelineConfigError, match="not transcribe_modular.v1"):
        run.apply_recipe(ap, ap.parse_args(argv[:2]), "transcribe_modular.v1", {}, argv[:2], c)


def test_the_index_records_a_recipes_expanded_pipeline(tmp_path):
    """The index records each recipe's pipeline, built from its pipeline template without the engines; ``verify``
    builds it again: a drift is a stale index, a pipeline that cannot be built a problem."""
    from linecaster.catalog import registry
    from linecaster.execution import provenance, run

    make(tmp_path)
    make_recipe(tmp_path)
    c = Catalog([tmp_path])
    built = c.recipe_pipeline("r")
    assert [b["component"] for b in built["pipeline"]] == ["ImageFolderReader", "PageRecognizer", "RecipeStamper",
                                                       "RejectWriter", "PageJsonlWriter"]
    recognizer = built["pipeline"][1]["params"]
    assert recognizer["backend"]["preset"] == "p" and "endpoint" not in recognizer["backend"]
    assert built["pipeline"][2]["params"] == {"recipe": "r", "recipe_sha256": c.resolve_recipe("r").sha256}
    c.write_index()
    assert yamlio.read(tmp_path / "catalog.index")["recipes"]["r"] == {
        "sha256": c.resolve_recipe("r").sha256, "pipeline_sha256": built["pipeline_sha256"]}
    # what the template builds into other folders is the same pipeline (in this process: the catalog put in place)
    from linecaster.templates import transcribe_vlm

    with registry.active(c):
        plan = run.describe(transcribe_vlm, ["IN", "ELSEWHERE", "--recipe", "r"], c)
    assert provenance.pipeline_sha256(plan) == built["pipeline_sha256"]
    assert Catalog([tmp_path]).verify() == []
    index = (tmp_path / "catalog.index").read_text()
    (tmp_path / "catalog.index").write_text(index.replace(built["pipeline_sha256"], "sha256:" + "1" * 64))
    assert any("catalog.index is stale (recipes r)" in p for p in Catalog([tmp_path]).verify())
    make_recipe(tmp_path, pipeline="transcribe_modular.v1")
    assert any("recipe r: its pipeline cannot be built" in p for p in Catalog([tmp_path]).verify())

