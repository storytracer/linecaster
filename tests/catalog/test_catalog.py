def test_yaml_12_booleans():
    assert yamlio.load("lang: [NO, yes, on]\nok: true\nv: '1.0'") == {"lang": ["NO", "yes", "on"], "ok": True,
                                                                       "v": "1.0"}
    assert yamlio.load(yamlio.dump({"x": "no", "y": "multi\nline"})) == {"x": "no", "y": "multi\nline"}


def test_yaml_duplicate_keys_are_errors():
    from ruamel.yaml.constructor import DuplicateKeyError

    with pytest.raises(DuplicateKeyError):
        yamlio.load("a: 1\na: 2\n")


def test_yaml_written_back_keeps_comments():
    doc = yamlio.load_rt("# head\nb: 1  # why\nc:\n  x: 1\n")
    yamlio.update(doc, {"a": 0, "b": 1, "c": {"x": 2}})
    text = yamlio.dump_rt(doc)
    assert text.startswith("# head\n") and "b: 1  # why" in text and yamlio.load(text) == {"a": 0, "b": 1, "c": {"x": 2}}
    assert list(yamlio.load(text)) == ["a", "b", "c"]          # a new key among sorted keys goes where it sorts


def make(root, temperature=0.0, prose="Why these settings."):
    up = root / "models" / "m" / "upstream" / "abc"
    up.mkdir(parents=True, exist_ok=True)
    (up / "README.md").write_text("---\nlicense: mit\n---\n# upstream card\n")
    write_entry(root / "models" / "m" / "model.yaml", {
        "schema": "linecaster.model", "id": "m", "source": {"kind": "hf", "ref": "org/m"},
        "pins": [{"revision": "abc", "pinned": dt.date(2026, 11, 3), "files": {"w.safetensors": "sha256:" + "0" * 64},
                  "card": "upstream/abc/README.md", "card_sha256": sha256_file(up / "README.md")}],
        "license": "MIT"}, "Ours.\n")
    write_entry(root / "presets" / "recognition" / "p.yaml", {
        "schema": "linecaster.preset", "id": "p", "step": "recognition",
        "model": {"id": "m", "revision": "abc"}, "engine": "chat.v1", "options": {"adapter": "lighton-ocr-2"},
        "settings": {"sampling": {"temperature": temperature}}, "capabilities": {"unit": "page"}, "support": "core"}, prose)


def test_the_index_shows_a_change_of_behaviour(tmp_path):
    """Entries carry no edition; ``catalog.index`` lists each entry's hash and ``verify`` fails when it is stale, so a
    change of behaviour shows in review. Prose is not functional."""
    make(tmp_path)
    c = Catalog([tmp_path])
    assert any("catalog.index is stale" in p for p in c.verify())             # a directory commits its index
    c.write_index()
    assert Catalog([tmp_path]).verify() == []
    index = yamlio.read(tmp_path / "catalog.index")
    assert index["presets"] == {"p": c.resolve("p").sha256}
    assert (tmp_path / "catalog.index").read_text().startswith("# generated by `linecaster catalog index`")
    assert c.resolve("p").content["model"] == {"id": "m", "revision": "abc",
                                               "files": {"w.safetensors": "sha256:" + "0" * 64}}
    make(tmp_path, prose="Better prose.")                  # prose is not functional: the index stands
    assert Catalog([tmp_path]).verify() == []
    make(tmp_path, temperature=0.2)                        # a functional change: the index must follow
    problems = Catalog([tmp_path]).verify()
    assert any("catalog.index is stale (presets p)" in p and "Changed outputs" not in p and "CHANGELOG" in p
               for p in problems)
    Catalog([tmp_path]).write_index()
    assert Catalog([tmp_path]).verify() == []

