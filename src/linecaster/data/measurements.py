"""The measurements vocabulary: every key a step may write into ``StepInfo.measurements``, with its meaning.

Measurements are numbers (and a few short values) a step records for one page: how long it took, what it cost in
tokens, what its rules changed. The vocabulary is fixed, so that the page records of different runs, engines and
releases can be compared key by key; a new key is added here before linecaster code writes it (a test fails on an
unknown one). Values vary from run to run and stay in the page records: the page files' provenance (ALTO, PAGE,
hOCR) carries the step records without them, apart from ``datetime``.
"""
from __future__ import annotations

#: the values of ``finish_reason``, as OpenAI-compatible servers report them (``None``: the server said nothing)
FINISH_REASONS = ("stop", "length", "content_filter", "tool_calls", "function_call", "abort", "repetition")

#: key -> meaning
MEASUREMENTS: dict[str, str] = {
    # any step
    "seconds": "wall time of the step on the page, in seconds (the engine's call, in-process or in the server); on the "
               "page record (Page.measurements), the page's time from its reader to its first writer, waiting "
               "included, summed over the runs that worked on the record (--after, --pages)",
    "datetime": "when the step started on the page, ISO 8601 in UTC (ALTO processingDateTime, PAGE date); on the page "
                "record, when the first run's reader handed it over",
    "device": "the device the step ran on, e.g. cuda:0 or cpu",
    # served steps
    "request_seconds": "a served step: from its request being built to its answer, in seconds (waiting for the "
                       "client's window, the HTTP round trip, the server's queue, decoding and model call; a page sent "
                       "again for a repair pass: to the last answer)",
    "queue_seconds": "a step served by linecaster serve: the request's wait in the server's queue for its model",
    "decode_seconds": "a step served by linecaster serve: the server's decoding of the page image",
    "decoder": "what decoded the page image the step read, e.g. nvImageCodec 0.10.0 (GPU 0) or Pillow 12.0.0 / "
               "OpenJPEG 2.5.4 (linecaster.images.pixels)",
    # vision-language models
    "prompt_tokens": "tokens of the prompt (image and text), summed over the page's requests",
    "completion_tokens": "tokens generated, summed over the page's requests",
    "finish_reason": f"why generation stopped: one of {', '.join(FINISH_REASONS)}, or None",
    "pass_prompt_tokens": "a page sent twice (the repair pass): the prompt tokens of each request, in order",
    "pass_completion_tokens": "a page sent twice (the repair pass): the tokens generated by each request, in order",
    "regions": "regions sent to the model (one request each)",
    "failed": "regions whose request failed",
    # importers
    "rules_matched": "an importer's conventions: rule id -> the nodes it matched on the page",
    "unmapped": "an importer's conventions: features of nodes no rule matched (an element's classes) -> how many",
    "anchored": "an importer: lines anchored in the source text, of all lines",
    "ends_paragraph": "an importer: the page's last paragraph ends on the page (true) or runs on onto the next",
    "table_continues": "an importer: the page's first block continues the previous page's table: with its rows "
                       "(rows), or in the middle of its last cell (cell)",
    "table_runs_on": "an importer: the page's last block is a table the next page continues",
    "starts_paragraph": "an importer: the page begins with a new paragraph or a block (true), not one that continues "
                        "the previous page's",
    "ill_formed_languages": "an importer: language values of the source that are no BCP 47 tag, skipped -> how often",
    "unexpanded": "an importer of a template language: the template calls it could not expand, by name",
    "wikidata": "a wiki's importer: the Wikidata ids a module asked about, which the importer never asks Wikidata",
    "texvc_rejected": "a wiki's importer: formulas MediaWiki's TeX checker (texvc) rejects, kept as written",
    # tables and formulas
    "tables": "table regions given a structure",
    "formulas": "formula regions read",
    # typography
    "body_size": "the page's body type size: the median row height of its text regions, in pixels",
    "leveled": "headings given a level",
    "demoted": "section headers set in body type, made text",
    "split": "headlines split off the text region they were merged into",
    "drop_capitals": "drop capitals linked to the line they begin (part_of)",
    "numbers_dropped": "page-number regions removed as uncertain (empty or below the confidence threshold)",
    # recomposition
    "paragraphs": "paragraphs made (a continued paragraph counts once)",
    "continuations": "paragraphs continued into the next region or page",
    "marks_removed": "division marks removed",
    "marks_kept": "hyphens at a row end kept",
    # tagging
    "tagged": "a tagger: the classifications it recorded, scheme -> value -> how many",
    "undecided": "a tagger: targets it recorded nothing for, its evidence not enough, scheme -> how many",
    "body_line_height": "the geometry tagger: the median height of the page's body text lines across their "
                        "direction, in pixels (what tiny compares with)",
    "asked": "the model tagger: requests sent, panel member -> how many (answers from the cache not counted)",
    "cached": "the model tagger: answers read from its cache, panel member -> how many",
    "agreed": "the model tagger: questions the panel's two members answered alike",
    "settled": "the model tagger: splits the third member and the scheme's rule decided",
}


def unknown_measurements(measurements: dict) -> list[str]:
    """The keys of ``measurements`` that are not in the vocabulary, and a ``finish_reason`` that is none of
    ``FINISH_REASONS``."""
    out = [k for k in measurements if k not in MEASUREMENTS]
    reason = measurements.get("finish_reason")
    if reason is not None and reason not in FINISH_REASONS:
        out.append(f"finish_reason={reason!r}")
    return out
