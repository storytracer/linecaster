#: engines linecaster itself provides: the chat presets' (behind an OpenAI-compatible server only), the rule-based
#: steps' and the single-region layout (``linecaster.engines``: in the pipeline's process only)
BUILTIN_ENGINES = {
    "chat.v1": "linecaster.adapters:ChatAdapter",
    "image.convert.v1": "linecaster.engines:ImageConvertEngine",
    "image.webp-lossless.v1": "linecaster.engines:WebpLosslessImageEngine",
    "layout.single-region.v1": "linecaster.engines:SingleRegionLayoutEngine",
    "normalization.latin-historic.v1": "linecaster.engines:LatinHistoricNormalizationEngine",
    "normalization.by-script.v1": "linecaster.engines:ByScriptNormalizationEngine",
    "typography.ratios.v1": "linecaster.engines:RatiosTypographyEngine",
    "recomposition.unicode.v1": "linecaster.engines:UnicodeRecompositionEngine",
    "recomposition.by-script.v1": "linecaster.engines:ByScriptRecompositionEngine",
    "composition.docling.v1": "linecaster.engines:DoclingCompositionEngine",
}
SERVED_ONLY = {"chat.v1"}
#: engines registered in this process, not installed (``linecaster.testing.register_fakes``: the fake engines)
REGISTERED: dict[str, str] = {}
#: engines never hosted by ``linecaster serve``: rules are cheaper than a request
IN_PROCESS_ONLY = set(BUILTIN_ENGINES) - SERVED_ONLY


def in_process_only(ref: str) -> bool:
    """Whether preset ``ref`` runs on a built-in engine that runs in the pipeline's process only."""
    return catalog().resolve(ref).engine in IN_PROCESS_ONLY


def engine_ids() -> dict[str, str]:
    """Returns every engine id with its class, ``module:Class``: linecaster's own and the installed engine packages'.

    linecaster's own are ``BUILTIN_ENGINES`` (``chat.v1``, the single-region layout and the rule-based engines);
    engine packages register theirs as entry points of the group ``linecaster.engines``; tests may register more in
    the process (``REGISTERED``, e.g. ``linecaster.testing.register_fakes``).

    Example:
        from linecaster.catalog import engine_ids

        engine_ids()["typography.ratios.v1"]      # 'linecaster.engines:RatiosTypographyEngine'
    """
    return {**BUILTIN_ENGINES, **{ep.name: ep.value for ep in entry_points(group="linecaster.engines")}, **REGISTERED}


def engine_class(engine: str):
    """Returns the class of an engine id, imported.

    An id that is neither built in nor installed (``engine_ids``) is a ``CatalogError`` naming the installed ones.

    Args:
        engine: the engine's id, e.g. ``kraken.recognition.v1``.

    Example:
        from linecaster.catalog import engine_class

        cls = engine_class("layout.single-region.v1")
        print(cls.step, cls.capabilities)
    """
    known = engine_ids()
    if engine not in known:
        from .code import install_hint

        hint = install_hint(engine)
        raise CatalogError(f"engine {engine!r} is not installed" + (f" ({hint})" if hint else "")
                           + f"; installed: {sorted(known)}")
    module, _, name = known[engine].partition(":")
    return getattr(import_module(module), name)


def engine_spec(ref: str, installed: bool = True, served: bool = False) -> tuple[str, dict, "Resolved"]:
    """Returns what runs a preset edition in-process: its engine class, keyword arguments and resolved edition.

    The keyword arguments are what ``InProcess`` and ``linecaster serve`` construct the engine with: the preset's
    options, plus ``weights`` (model, source, revision and files of the model pin) for a preset with a model (and
    ``submodel_weights`` by role), plus ``strategies`` (script -> engine, options, preset edition and hash) for a
    by-script preset. Engines with weights fetch exactly that pin. A chat preset (``chat.v1``) is a
    ``CatalogError``: it runs behind a server (``linecaster.adapters.chat_model``); so is a preset whose engine is
    not installed, unless ``installed=False`` (the error names the engine package that provides it and the pipeline
    scripts that install it).

    Args:
        ref: the preset, ``id@edition`` (``id`` alone: its current edition).
        installed: ``False`` (describing a pipeline without its engines): an engine that is not installed here is
            named by its class in the repository's engine packages (``catalog.code``), else by its id.
        served: for ``linecaster serve``, which hosts no in-process-only engine: such a preset is a
            ``CatalogError``.

    Example:
        from linecaster.backends import InProcess
        from linecaster.catalog import engine_spec

        spec, kwargs, resolved = engine_spec("ratios@1")
        backend = InProcess(spec, **kwargs)        # what InProcess.from_preset("ratios@1") builds
        print(spec, resolved.ref, resolved.sha256)
    """
    r = catalog().resolve(ref)
    known = engine_ids()
    if r.engine in SERVED_ONLY:
        raise CatalogError(f"preset {r.ref} ({r.engine}) runs behind a server: use linecaster.adapters.chat_model")
    if served and r.engine in IN_PROCESS_ONLY:
        raise CatalogError(f"preset {r.ref} ({r.engine}) is built in and runs in the pipeline's process only; "
                           "linecaster serve hosts models")
    if r.engine not in known and not installed:
        from . import code

        sources = code.engines() if code.REPO is not None else {}
        known = {**known, r.engine: sources[r.engine].target if r.engine in sources else r.engine}
    if r.engine not in known:
        from .code import install_hint

        hint = install_hint(r.engine)
        raise CatalogError(f"preset {r.ref} needs engine {r.engine!r}, which is not installed" + (f": {hint}" if hint else ""))
    kwargs = dict(r.content.get("options", {}))

    def weights(pin: dict) -> dict:
        m = catalog().model(pin["id"])
        return {"model": m.id, "source": m.source.model_dump(), "revision": pin["revision"], "files": pin["files"]}

    if r.content.get("model"):
        kwargs["weights"] = weights(r.content["model"])
    if r.content.get("submodels"):
        kwargs["submodel_weights"] = {role: weights(pin) for role, pin in r.content["submodels"].items()}
    if r.content.get("by_script"):
        kwargs["strategies"] = {}
        for code, s in r.content["by_script"].items():
            spec, options, sr = engine_spec(s["ref"], installed)
            kwargs["strategies"][code] = {"engine": spec, "options": options, "preset": sr.ref,
                                          "preset_sha256": sr.sha256}
    return known[r.engine], kwargs, r




_POLICIES: dict = {}


def rendering_policy(ref: str):
    """The rendering policy ``ref`` of the catalog, cached for the process (``Catalog.policy``)."""
    if ref not in _POLICIES:
        _POLICIES[ref] = catalog().policy(ref)
    return _POLICIES[ref]
