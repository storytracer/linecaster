def schema_problems(folder: Path = SCHEMA_DIR) -> list[str]:
    """The committed JSON Schemas against fresh ones from the models."""
    fresh = json_schemas()
    problems = [f"schema {name} differs from the models: run `linecaster catalog schemas`"
                for name, text in fresh.items()
                if not (folder / name).exists() or (folder / name).read_text(encoding="utf-8") != text]
    problems += [f"schema {p.name} belongs to no format" for p in sorted(folder.glob("*.json")) if p.name not in fresh]
    return problems


def file_problems(d: Directory) -> list[str]:
    """The files of a catalog directory: each YAML file names its schema in its first line; Markdown files are
    prose next to a YAML file, without front matter; core presets and recipes have their prose."""
    problems = []
    for path, sid in sorted(d.files.items()):
        want = (SCHEMA_DIR / schema_file(sid)).resolve()
        named = yamlio.modeline(path)
        if named is None:
            problems.append(f"{path.relative_to(d.root)}: the first line does not name its schema "
                            f"({modeline(path, sid)})")
        elif (path.parent / named).resolve() != want:
            problems.append(f"{path.relative_to(d.root)}: names schema {named}, not {schema_file(sid)}")
    for md in sorted([*d.root.glob("presets/*/*.md"), *d.root.glob("recipes/*.md"), *d.root.glob("models/*/*.md"),
                      *d.root.glob("conventions/*/*.md")]):
        rel = md.relative_to(d.root)
        if not md.with_suffix(".yaml").exists():
            problems.append(f"{rel}: Markdown without its YAML file ({md.with_suffix('.yaml').name})")
        elif md.read_text(encoding="utf-8").startswith("---\n"):
            problems.append(f"{rel}: front matter in the prose; data belongs in {md.with_suffix('.yaml').name}")
    for f in sorted([*d.root.glob("presets/*/*"), *d.root.glob("recipes/*")]):
        if f.is_file() and f.suffix not in (".yaml", ".md") and f.name != ".gitkeep":
            problems.append(f"{f.relative_to(d.root)}: neither YAML nor Markdown")
    for kind in KINDS:
        for eid, doc in d.entries[kind.name].items():
            body = d.bodies[kind.name][eid]
            where = d.paths[kind.name][eid].with_suffix(".md").relative_to(d.root)
            if kind.prose_required(doc) and not body.strip():
                level = f" ({doc.support})" if hasattr(doc, "support") else ""
                problems.append(f"{kind.name} {eid}{level}: its prose is missing ({where})")
            elif kind.name == "conventions":
                missing = [h for h in CONVENTIONS_HEADINGS if h not in body.splitlines()]
                if missing:
                    problems.append(f"conventions {eid}: its prose lacks the headings {missing} ({where})")
    return problems


@dataclass(frozen=True)
class Resolved:
    """A preset or recipe as this release runs it: id, functional content and its hash."""

    id: str
    content: dict
    sha256: str

    @property
    def ref(self) -> str:
        return self.id

    def checked(self, sha256: str | None) -> "Resolved":
        """Itself; a ``sha256`` (a run record's) that differs is a warning: the entry changed since that run."""
        if sha256 is not None and sha256 != self.sha256:
            warnings.warn(f"{self.id} has the hash {self.sha256} in this release, the record names {sha256}: it "
                          f"changed since that run (rerun it with the linecaster version its record names)",
                          EditionWarning, stacklevel=3)
        return self

    @property
    def engine(self) -> str:
        return self.content["engine"]


@dataclass(frozen=True)
class ResolvedNormalization:
    """A normalization as this release has it: its rule, the hash of it, what it is for, what it subsumes."""

    id: str
    rule: dict
    sha256: str
    use: tuple[str, ...]
    subsumes: tuple[str, ...] = ()
    languages: tuple[str, ...] = ()

    @property
    def text_rule(self) -> bool:
        """Whether it acts on characters (``linecaster.text.normalize``), not on a document's structure."""
        from .schema import TEXT_RULES

        return next(iter(self.rule)) in TEXT_RULES


@dataclass(frozen=True)
class ResolvedStrategy:
    """A transcription strategy as it runs: its name (a strategy's id, ``literal``, or normalizations joined by
    ``+``), what it is for, and its normalizations in order."""

    id: str
    use: str
    normalizations: tuple[ResolvedNormalization, ...]

    @property
    def content(self) -> dict:
        return {"use": self.use, "normalizations": [{"id": n.id, "sha256": n.sha256} for n in self.normalizations]}

    @property
    def sha256(self) -> str:
        return canonical_sha256(self.content)

    @property
    def literal(self) -> bool:
        return not self.normalizations

    def text(self, s: str) -> str:
        """``s`` through the strategy's normalizations (character rules only: a structure rule acts on documents,
        ``linecaster.document.strategy``)."""
        from ..text.normalize import apply

        return apply(s or "", [n.rule for n in self.normalizations])

    def covers(self, nid: str) -> bool:
        """Whether the strategy applies normalization ``nid``, itself or one that subsumes it."""
        return any(n.id == nid or nid in n.subsumes for n in self.normalizations)


@lru_cache(maxsize=1)
def _installed() -> Catalog:
    return Catalog()


#: catalogs ``active()`` put in place of the installed one (innermost last)
_ACTIVE: list[Catalog] = []


def catalog() -> Catalog:
    """Returns the installed catalog, or the one ``active()`` puts in its place.

    The installed catalog is ``src/linecaster/catalog/data/``, read once and cached; ``catalog.cache_clear()``
    reads it again after its files changed.

    Example:
        from linecaster.catalog import catalog

        c = catalog()
        r = c.resolve("kraken-ppocrv6-medium")
        print(r.ref, r.sha256, c.preset("kraken-ppocrv6-medium").engine)
    """
    return _ACTIVE[-1] if _ACTIVE else _installed()


catalog.cache_clear = _installed.cache_clear


@contextmanager
def active(c: Catalog):
    """``catalog()`` is ``c`` inside (describing a recipe of another catalog directory)."""
    _ACTIVE.append(c)
    try:
        yield c
    finally:
        _ACTIVE.pop()


