"""Loading, resolving, releasing and verifying the catalogue (``docs/reference/catalog.md``).

A catalogue directory holds ``models/<id>/model.md`` (+ ``upstream/<revision>/``), ``presets/<id>.md``,
``evidence/*.yaml`` and ``catalog.lock``. linecaster's own is ``linecaster/catalog/data``; engine packages add
theirs through the entry-point group ``linecaster.catalog`` (the entry point names a function returning the
directory). Engines are found through the group ``linecaster.engines`` (engine id -> ``module:Class``).
"""
from __future__ import annotations

import datetime as dt
import hashlib
import json
from dataclasses import dataclass, field
from functools import lru_cache
from importlib import import_module
from importlib.metadata import entry_points
from pathlib import Path
from typing import Any

from . import yamlio
from .schema import Evidence, Lock, LockEntry, ModelDoc, PresetDoc, RecipeDoc

CORE = Path(__file__).resolve().parent / "data"
LOCK = "catalog.lock"
#: the preset fields that can change outputs; everything else is description
FUNCTIONAL = ("step", "model", "submodels", "engine", "options", "settings", "labels", "serve")


def sha256_file(path: str | Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return f"sha256:{h.hexdigest()}"


def canonical_sha256(data: Any) -> str:
    blob = json.dumps(data, sort_keys=True, separators=(",", ":"), ensure_ascii=False, default=str)
    return f"sha256:{hashlib.sha256(blob.encode()).hexdigest()}"


def split_ref(ref: str) -> tuple[str, int | None]:
    """``id@edition`` -> (id, edition); ``id`` -> (id, None)."""
    if "@" in ref:
        pid, ed = ref.rsplit("@", 1)
        return pid, int(ed)
    return ref, None


@dataclass
class Directory:
    """One catalogue directory and the documents it holds."""

    root: Path
    models: dict[str, ModelDoc] = field(default_factory=dict)
    model_bodies: dict[str, str] = field(default_factory=dict)
    presets: dict[str, PresetDoc] = field(default_factory=dict)
    preset_bodies: dict[str, str] = field(default_factory=dict)
    recipes: dict[str, RecipeDoc] = field(default_factory=dict)
    recipe_bodies: dict[str, str] = field(default_factory=dict)
    evidence: list[tuple[Path, Evidence]] = field(default_factory=list)
    lock: Lock = field(default_factory=Lock)

    @classmethod
    def load(cls, root: str | Path) -> "Directory":
        d = cls(Path(root))
        for p in sorted(d.root.glob("models/*/model.md")):
            meta, body = yamlio.read_front_matter(p)
            m = _validate(ModelDoc, meta, p)
            if m.id != p.parent.name:
                raise ValueError(f"{p}: id {m.id!r} differs from its folder {p.parent.name!r}")
            d.models[m.id], d.model_bodies[m.id] = m, body
        for p in sorted(d.root.glob("presets/*/*.md")):            # presets/<step>/<id>.md
            meta, body = yamlio.read_front_matter(p)
            pr = _validate(PresetDoc, meta, p)
            if pr.id != p.stem:
                raise ValueError(f"{p}: id {pr.id!r} differs from its file name {p.stem!r}")
            if pr.step != p.parent.name:
                raise ValueError(f"{p}: step {pr.step!r} differs from its folder {p.parent.name!r}")
            d.presets[pr.id], d.preset_bodies[pr.id] = pr, body
        for p in sorted(d.root.glob("recipes/*.md")):
            meta, body = yamlio.read_front_matter(p)
            rc = _validate(RecipeDoc, meta, p)
            if rc.id != p.stem:
                raise ValueError(f"{p}: id {rc.id!r} differs from its file name {p.stem!r}")
            d.recipes[rc.id], d.recipe_bodies[rc.id] = rc, body
        for p in sorted(d.root.glob("evidence/*.yaml")):
            d.evidence.append((p, _validate(Evidence, yamlio.load(p.read_text(encoding="utf-8")), p)))
        lock = d.root / LOCK
        if lock.exists():
            d.lock = _validate(Lock, yamlio.load(lock.read_text(encoding="utf-8")) or {}, lock)
        return d

    def save_lock(self) -> None:
        data = self.lock.model_dump(mode="json", by_alias=True)
        data["presets"] = dict(sorted(data["presets"].items()))
        data["recipes"] = dict(sorted(data["recipes"].items()))
        if not data["recipes"]:
            data.pop("recipes")
        (self.root / LOCK).write_text("# generated by `linecaster catalog release`; never edited by hand\n"
                                      + yamlio.dump(data), encoding="utf-8")


def _validate(model, data, path):
    try:
        return model.model_validate(data)
    except Exception as e:  # noqa: BLE001 - name the file
        raise ValueError(f"{path}: {e}") from e


class Catalog:
    """The catalogue (linecaster's own, ``CORE``); other directories only for tests. Ids are unique."""

    def __init__(self, dirs: list[str | Path] | None = None):
        self.dirs = [Directory.load(d) for d in (dirs if dirs is not None else [CORE])]
        self.models: dict[str, tuple[Directory, ModelDoc]] = {}
        self.presets: dict[str, tuple[Directory, PresetDoc]] = {}
        self.recipes: dict[str, tuple[Directory, RecipeDoc]] = {}
        for d in self.dirs:
            for kind, src, dst in (("model", d.models, self.models), ("preset", d.presets, self.presets),
                                   ("recipe", d.recipes, self.recipes)):
                for k, v in src.items():
                    if k in dst:
                        raise ValueError(f"{kind} {k!r} in both {dst[k][0].root} and {d.root}")
                    dst[k] = (d, v)
        both = set(self.presets) & set(self.recipes)
        if both:
            raise ValueError(f"ids used for a preset and a recipe: {sorted(both)}")

    # -------------------------------------------------------------------------------------------- lookups

    def model(self, mid: str) -> ModelDoc:
        try:
            return self.models[mid][1]
        except KeyError:
            raise KeyError(f"unknown model {mid!r}; known: {sorted(self.models)}") from None

    def preset(self, pid: str) -> PresetDoc:
        try:
            return self.presets[pid][1]
        except KeyError:
            raise KeyError(f"unknown preset {pid!r}; known: {sorted(self.presets)}") from None

    def recipe(self, rid: str) -> RecipeDoc:
        try:
            return self.recipes[rid][1]
        except KeyError:
            raise KeyError(f"unknown recipe {rid!r}; known: {sorted(self.recipes)}") from None

    def recipe_functional(self, rc: RecipeDoc) -> dict:
        """A recipe's functional content: its pipeline, each slot's preset edition with that edition's hash
        (which covers its model pin), and the options it states."""
        data = rc.model_dump(mode="json", by_alias=True, include={"pipeline", "options"}, exclude_unset=True)
        data["presets"] = {slot: {"ref": ref, "sha256": self.resolve(ref).sha256}
                           for slot, ref in sorted(rc.presets.items())}
        return data

    def resolve_recipe(self, ref: str) -> "Resolved":
        """A recipe edition: the current file when its edition matches, else the lock."""
        rid, edition = split_ref(ref)
        if rid not in self.recipes:
            raise KeyError(f"unknown recipe {rid!r}; known: {sorted(self.recipes)}")
        d, rc = self.recipes[rid]
        if edition is None or edition == rc.edition:
            content = self.recipe_functional(rc)
            return Resolved(rid, rc.edition, content, canonical_sha256(content),
                            released=rc.ref in d.lock.recipes)
        entry = d.lock.recipes.get(f"{rid}@{edition}")
        if entry is None:
            raise KeyError(f"{rid}@{edition} is neither the current edition ({rc.edition}) nor released")
        return Resolved(rid, edition, entry.resolved, entry.sha256, released=True)

    def body(self, pid: str) -> str:
        """The Markdown body of preset ``pid`` (the reasons, limitations, changes)."""
        return self.presets[pid][0].preset_bodies[pid]

    def functional(self, p: PresetDoc) -> dict:
        """The preset's functional content, with the model pin resolved to revision and files."""
        # only what the document states: a new optional schema field must not change released hashes
        data = p.model_dump(mode="json", by_alias=True, include=set(FUNCTIONAL), exclude_unset=True)
        if p.model is not None:
            data["model"] = self._pin(p.model)
        if p.submodels:
            data["submodels"] = {role: self._pin(ref) for role, ref in sorted(p.submodels.items())}
        return data

    def _pin(self, ref) -> dict:
        pin = self.model(ref.id).pin(ref.revision)
        return {"id": ref.id, "revision": pin.revision, "files": dict(sorted(pin.files.items()))}

    def resolve(self, ref: str) -> "Resolved":
        """A preset edition: the current file when its edition matches (released or draft), else the lock."""
        pid, edition = split_ref(ref)
        d, p = self.presets[pid] if pid in self.presets else (None, None)
        if p is None:
            raise KeyError(f"unknown preset {pid!r}; known: {sorted(self.presets)}")
        if edition is None or edition == p.edition:
            content = self.functional(p)
            return Resolved(pid, p.edition, content, canonical_sha256(content), released=f"{pid}@{p.edition}" in d.lock.presets)
        entry = d.lock.presets.get(f"{pid}@{edition}")
        if entry is None:
            raise KeyError(f"{pid}@{edition} is neither the current edition ({p.edition}) nor released")
        return Resolved(pid, edition, entry.resolved, entry.sha256, released=True)

    # --------------------------------------------------------------------------------------- release, verify

    def release(self, pid: str, commit: str | None = None, today: dt.date | None = None) -> LockEntry:
        """Freeze the current edition of preset or recipe ``pid`` in its catalogue's ``catalog.lock``. A recipe
        is released only on released preset editions."""
        if pid in self.recipes:
            d, doc = self.recipes[pid]
            unreleased = [r for r in doc.presets.values() if not self.resolve(r).released]
            if unreleased:
                raise ValueError(f"recipe {doc.ref}: release its presets first: {unreleased}")
            table, content, kind = d.lock.recipes, self.recipe_functional(doc), "recipe"
        else:
            d, doc = self.presets[pid]
            table, content, kind = d.lock.presets, self.functional(doc), "preset"
        key, sha = doc.ref, canonical_sha256(content)
        old = table.get(key)
        if old is not None:
            if old.sha256 != sha:
                raise ValueError(f"{key} is released with other content; give the {kind} edition {doc.edition + 1}")
            return old
        entry = LockEntry(sha256=sha, released=today or dt.date.today(), linecaster=commit, resolved=content)
        table[key] = entry
        d.save_lock()
        return entry

    def verify(self, files: bool = True) -> list[str]:
        """Every problem in the catalogue, as messages (empty: all good)."""
        problems = []
        for d in self.dirs:
            for mid, m in d.models.items():
                for pin in m.pins:
                    card = d.root / "models" / mid / pin.card
                    if not card.exists():
                        problems.append(f"model {mid}: card {pin.card} is missing")
                    elif files and sha256_file(card) != pin.card_sha256:
                        problems.append(f"model {mid}: card {pin.card} differs from its pinned sha256")
                    if pin.license_file and not (d.root / "models" / mid / pin.license_file).exists():
                        problems.append(f"model {mid}: licence file {pin.license_file} is missing")
            for pid, p in d.presets.items():
                bad = []
                for ref in ([p.model] if p.model is not None else []) + list(p.submodels.values()):
                    try:
                        self.model(ref.id).pin(ref.revision)
                    except KeyError as e:
                        bad.append(f"preset {pid}: {e.args[0]}")
                if bad:
                    problems += bad
                    continue
                if p.superseded_by and split_ref(p.superseded_by)[0] not in self.presets:
                    problems.append(f"preset {pid}: superseded_by {p.superseded_by!r} is unknown")
                family = p.engine.split(".")[0]
                known = engine_ids()
                if p.engine not in known and any(k.split(".")[0] == family for k in known):
                    problems.append(f"preset {pid}: engine {p.engine!r} is not registered "
                                    f"({sorted(k for k in known if k.split('.')[0] == family)} are)")
                entry = d.lock.presets.get(p.ref)
                if entry is not None and entry.sha256 != canonical_sha256(self.functional(p)):
                    problems.append(f"preset {p.ref} is released, but its functional content changed: "
                                    f"give it edition {p.edition + 1}")
                for key in d.lock.presets:
                    kid, ked = split_ref(key)
                    if kid == pid and ked > p.edition:
                        problems.append(f"preset {pid}: edition {ked} is released but the file is at {p.edition}")
            for rid, rc in d.recipes.items():
                try:
                    content = self.recipe_functional(rc)
                except KeyError as e:
                    problems.append(f"recipe {rid}: {e.args[0]}")
                    continue
                unreleased = [r for r in rc.presets.values() if not self.resolve(r).released]
                if unreleased:
                    problems.append(f"recipe {rid}: preset editions not released: {unreleased}")
                if rc.superseded_by and split_ref(rc.superseded_by)[0] not in self.recipes:
                    problems.append(f"recipe {rid}: superseded_by {rc.superseded_by!r} is unknown")
                entry = d.lock.recipes.get(rc.ref)
                if entry is not None and entry.sha256 != canonical_sha256(content):
                    problems.append(f"recipe {rc.ref} is released, but its functional content changed: "
                                    f"give it edition {rc.edition + 1}")
            for key, entry in [*d.lock.presets.items(), *d.lock.recipes.items()]:
                if canonical_sha256(entry.resolved) != entry.sha256:
                    problems.append(f"lock {key}: its resolved content does not match its sha256")
            for path, ev in d.evidence:
                try:
                    (self.resolve if ev.preset else self.resolve_recipe)(ev.subject)
                except KeyError as e:
                    problems.append(f"evidence {path.name}: {e.args[0]}")
        return problems


@dataclass(frozen=True)
class Resolved:
    """A preset edition as it runs: id, edition, functional content and its hash."""

    id: str
    edition: int
    content: dict
    sha256: str
    released: bool

    @property
    def ref(self) -> str:
        return f"{self.id}@{self.edition}"

    @property
    def engine(self) -> str:
        return self.content["engine"]


@lru_cache(maxsize=1)
def catalog() -> Catalog:
    """The installed catalogue (cached; ``catalog.cache_clear()`` after changing documents)."""
    return Catalog()


# ----------------------------------------------------------------------------------------------- engines

#: engines linecaster itself provides; chat presets run behind an OpenAI-compatible server only
BUILTIN_ENGINES = {"chat.v1": "linecaster.adapters:ChatAdapter"}
SERVED_ONLY = {"chat.v1"}


def engine_ids() -> dict[str, str]:
    """Engine ids -> ``module:Class``: linecaster's own and the installed ones (``linecaster.engines``)."""
    return {**BUILTIN_ENGINES, **{ep.name: ep.value for ep in entry_points(group="linecaster.engines")}}


def engine_class(engine: str):
    known = engine_ids()
    if engine not in known:
        raise KeyError(f"engine {engine!r} is not installed; installed: {sorted(known)}")
    module, _, name = known[engine].partition(":")
    return getattr(import_module(module), name)


def engine_spec(ref: str) -> tuple[str, dict, "Resolved"]:
    """``module:Class``, keyword arguments and the resolved edition for preset ``ref`` (what ``InProcess``
    and ``linecaster serve`` take): the engine's options, plus ``weights`` (source, revision and files of the
    model pin) for presets with a model. Engines with weights take ``weights`` and fetch exactly that pin."""
    r = catalog().resolve(ref)
    known = engine_ids()
    if r.engine in SERVED_ONLY:
        raise ValueError(f"preset {r.ref} ({r.engine}) runs behind a server: use linecaster.adapters.chat_model")
    if r.engine not in known:
        raise KeyError(f"preset {r.ref} needs engine {r.engine!r}, which is not installed")
    kwargs = dict(r.content.get("options", {}))

    def weights(pin: dict) -> dict:
        m = catalog().model(pin["id"])
        return {"model": m.id, "source": m.source.model_dump(), "revision": pin["revision"], "files": pin["files"]}

    if r.content.get("model"):
        kwargs["weights"] = weights(r.content["model"])
    if r.content.get("submodels"):
        kwargs["submodel_weights"] = {role: weights(pin) for role, pin in r.content["submodels"].items()}
    return known[r.engine], kwargs, r


