"""Loading, resolving, indexing and verifying the catalog (``docs/reference/catalog.md``).

A catalog directory holds ``models/<id>/model.yaml`` (+ ``upstream/<revision>/``), ``presets/<step>/<id>.yaml``,
``recipes/<id>.yaml``, ``policies/<id>.yaml``, ``conventions/<format>/<id>.yaml`` and ``catalog.index`` (no evidence
records: an evaluation keeps those); a model, preset or recipe may have its prose in a Markdown file next to it
(``model.md``, ``<id>.md``), which only the docs read.

Entries carry no edition: the linecaster release versions them (``docs/reference/compatibility.md``). An entry is
identified by its id and, for what it does, by the hash of its functional content; ``catalog.index`` (generated by
``linecaster catalog index``, committed) lists every entry's hash, so a change of behaviour shows in review, and
``verify`` fails when it is stale. A reference from before 0.10 (``id@edition``) resolves to this release's entry,
with a warning (``entry_id``). There is one catalog,
linecaster's own, ``linecaster/catalog/data``: engine packages and derivatives ship none (other directories are
for tests). Engines are found through the entry-point group ``linecaster.engines`` (engine id -> ``module:Class``),
plus linecaster's own (``BUILTIN_ENGINES``).
"""
