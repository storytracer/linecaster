def sha256_file(path: str | Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return f"sha256:{h.hexdigest()}"


def canonical_sha256(data: Any) -> str:
    blob = json.dumps(data, sort_keys=True, separators=(",", ":"), ensure_ascii=False, default=str)
    return f"sha256:{hashlib.sha256(blob.encode()).hexdigest()}"


class EditionWarning(UserWarning):
    """A reference names a catalog edition (``id@N``, before linecaster 0.10); it resolves to this release's entry."""


_WARNED: set[str] = set()


def entry_id(ref: str) -> str:
    """The entry a reference names: ``id``, or ``id@N`` from before 0.10, whose edition is dropped with a warning
    (once per reference): catalog entries carry no edition, the release versions them, so ``squiddle`` is this
    release's ``squiddle``, which may differ from what 0.9 ran (reproduce that with the version its record names)."""
    eid, at, edition = ref.rpartition("@")
    if not at or not edition.isdigit():
        return ref
    if ref not in _WARNED:
        _WARNED.add(ref)
        warnings.warn(f"{ref}: catalog entries carry no edition since linecaster 0.10; it resolves to this release's "
                      f"{eid!r}", EditionWarning, stacklevel=2)
    return eid


def modeline(path: str | Path, schema_id: str) -> str:
    """The first line of a catalog file at ``path``: its JSON Schema, relative to the file."""
    rel = os.path.relpath(SCHEMA_DIR / schema_file(schema_id), Path(path).resolve().parent)
    return yamlio.MODELINE.format(Path(rel).as_posix())


def write_entry(path: str | Path, data: dict, prose: str | None = None) -> Path:
    """A catalog entry as ``path`` (YAML, its schema named in the first line) and, with ``prose``, the Markdown
    file next to it (``.md``; removed when ``prose`` is empty)."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(modeline(path, data["schema"]) + "\n" + yamlio.dump(data), encoding="utf-8")
    if prose is not None:
        md = path.with_suffix(".md")
        if prose.strip():
            md.write_text(prose.strip("\n").rstrip() + "\n", encoding="utf-8")
        else:
            md.unlink(missing_ok=True)
    return path


def _prose(path: Path) -> str:
    md = path.with_suffix(".md")
    return md.read_text(encoding="utf-8") if md.exists() else ""


@dataclass(frozen=True)
class EntryKind:
    """One kind of catalog entry: where its files are, its format, how its id is checked against its path, its
    table in the index (``None``: not indexed, as models, whose pins the presets' hashes cover), and whether its
    Markdown prose is required."""

    name: str
    pattern: str
    model: type
    id_of: Any                                   # path -> the id the file must have
    folder_check: Any = None                     # (path, doc) -> a problem, or None
    index_table: str | None = None
    prose_required: Any = lambda doc: False      # doc -> whether its prose must exist


def _preset_folder(path: Path, doc) -> str | None:
    return None if doc.step == path.parent.name else f"step {doc.step!r} differs from its folder {path.parent.name!r}"


def _conventions_folder(path: Path, doc) -> str | None:
    return None if doc.format == path.parent.name else \
        f"format {doc.format!r} differs from its folder {path.parent.name!r}"


#: the kinds of catalog entry, in loading order
KINDS: tuple[EntryKind, ...] = (
    EntryKind("model", "models/*/model.yaml", ModelDoc, lambda path: path.parent.name),
    EntryKind("preset", "presets/*/*.yaml", PresetDoc, lambda path: path.stem, _preset_folder, "presets",
              lambda doc: doc.support in PROSE_REQUIRED),
    EntryKind("recipe", "recipes/*.yaml", RecipeDoc, lambda path: path.stem, None, "recipes",
              lambda doc: doc.support in PROSE_REQUIRED),
    EntryKind("policy", "policies/*.yaml", PolicyDoc, lambda path: path.stem, None, "policies"),
    EntryKind("conventions", "conventions/*/*.yaml", ConventionsDoc, lambda path: path.stem, _conventions_folder,
              "conventions", lambda doc: True),
    EntryKind("normalization", "normalizations/*.yaml", NormalizationDoc, lambda path: path.stem, None,
              "normalizations"),
    EntryKind("strategy", "strategies/*.yaml", StrategyDoc, lambda path: path.stem, None, "strategies"),
)
KIND = {k.name: k for k in KINDS}
#: the headings every conventions entry's prose has
CONVENTIONS_HEADINGS = ("## Source", "## How the markup works", "## Not in the rules", "## Open questions")


@dataclass
class Directory:
    """One catalog directory and the entries it holds, by kind (``entries``), with their Markdown prose
    (``bodies``) and their paths (``paths``)."""

    root: Path
    entries: dict[str, dict[str, Any]] = field(default_factory=lambda: {k.name: {} for k in KINDS})
    bodies: dict[str, dict[str, str]] = field(default_factory=lambda: {k.name: {} for k in KINDS})
    paths: dict[str, dict[str, Path]] = field(default_factory=lambda: {k.name: {} for k in KINDS})
    #: every YAML file read, with its schema id
    files: dict[Path, str] = field(default_factory=dict)

    @property
    def models(self) -> dict[str, ModelDoc]:
        return self.entries["model"]

    @property
    def presets(self) -> dict[str, PresetDoc]:
        return self.entries["preset"]

    @property
    def recipes(self) -> dict[str, RecipeDoc]:
        return self.entries["recipe"]

    @property
    def policies(self) -> dict[str, PolicyDoc]:
        return self.entries["policy"]

    @property
    def conventions(self) -> dict[str, ConventionsDoc]:
        return self.entries["conventions"]

    @property
    def normalizations(self) -> dict[str, NormalizationDoc]:
        return self.entries["normalization"]

    @property
    def strategies(self) -> dict[str, StrategyDoc]:
        return self.entries["strategy"]

    @classmethod
    def load(cls, root: str | Path) -> "Directory":
        d = cls(Path(root))
        for kind in KINDS:
            for p in sorted(d.root.glob(kind.pattern)):
                doc = d._read(kind.model, p)
                if doc.id != kind.id_of(p):
                    raise CatalogError(f"{p}: id {doc.id!r} differs from its path ({kind.id_of(p)!r})")
                problem = kind.folder_check(p, doc) if kind.folder_check else None
                if problem:
                    raise CatalogError(f"{p}: {problem}")
                d.entries[kind.name][doc.id] = doc
                d.bodies[kind.name][doc.id] = _prose(p)
                d.paths[kind.name][doc.id] = p
        return d

    def _read(self, model, path: Path):
        try:
            data = yamlio.read(path)
        except Exception as e:  # noqa: BLE001 - name the file
            raise CatalogError(f"{path}: {e}") from e
        doc = _validate(model, data, path)
        self.files[path] = doc.schema_
        return doc

    def read_index(self) -> dict | None:
        """The committed index (``catalog.index``), or ``None`` without one."""
        path = self.root / INDEX
        return yamlio.read(path) if path.exists() else None

    def save_index(self, data: dict) -> Path:
        path = self.root / INDEX
        path.write_text(f"{INDEX_COMMENT}\n{yamlio.dump(data)}", encoding="utf-8")
        return path


def _validate(model, data, path):
    try:
        return model.model_validate(data)
    except Exception as e:  # noqa: BLE001 - name the file
        raise CatalogError(f"{path}: {e}") from e


class Catalog:
    """The catalog (linecaster's own, ``CORE``); other directories only for tests. Ids are unique."""

    def __init__(self, dirs: list[str | Path] | None = None):
        self.dirs = [Directory.load(d) for d in (dirs if dirs is not None else [CORE])]
        #: kind -> id -> (the directory it is in, the entry)
        self.index: dict[str, dict[str, tuple[Directory, Any]]] = {k.name: {} for k in KINDS}
        for d in self.dirs:
            for kind in KINDS:
                dst = self.index[kind.name]
                for k, v in d.entries[kind.name].items():
                    if k in dst:
                        raise CatalogError(f"{kind.name} {k!r} in both {dst[k][0].root} and {d.root}")
                    dst[k] = (d, v)
        both = set(self.presets) & set(self.recipes)
        if both:
            raise CatalogError(f"ids used for a preset and a recipe: {sorted(both)}")

    @property
    def models(self) -> dict[str, tuple[Directory, ModelDoc]]:
        return self.index["model"]

    @property
    def presets(self) -> dict[str, tuple[Directory, PresetDoc]]:
        return self.index["preset"]

    @property
    def recipes(self) -> dict[str, tuple[Directory, RecipeDoc]]:
        return self.index["recipe"]

    @property
    def policies(self) -> dict[str, tuple[Directory, PolicyDoc]]:
        return self.index["policy"]

    @property
    def conventions_entries(self) -> dict[str, tuple[Directory, ConventionsDoc]]:
        return self.index["conventions"]

    @property
    def normalizations(self) -> dict[str, tuple[Directory, NormalizationDoc]]:
        return self.index["normalization"]

    @property
    def strategies(self) -> dict[str, tuple[Directory, StrategyDoc]]:
        return self.index["strategy"]

    # ------------------------------------------------------------------------------ normalizations, strategies

    @staticmethod
    def normalization_functional(doc: NormalizationDoc) -> dict:
        """A normalization's functional content: its rule (not its description, scripts, languages, use)."""
        return {"rule": doc.rule.model_dump(mode="json", exclude_none=True)}

    def normalization(self, nid: str) -> "ResolvedNormalization":
        """The normalization ``nid``, resolved: its rule, hash, uses and what it subsumes."""
        nid = entry_id(nid)
        if nid not in self.normalizations:
            raise CatalogError(f"unknown normalization {nid!r}; known: {sorted(self.normalizations)}")
        doc = self.normalizations[nid][1]
        content = self.normalization_functional(doc)
        return ResolvedNormalization(nid, content["rule"], canonical_sha256(content), tuple(doc.use),
                                    tuple(doc.subsumes), tuple(doc.languages))

    def strategy(self, ref: str, use: str | None = None) -> "ResolvedStrategy":
        """The transcription strategy ``ref``: ``literal`` (no normalization), a strategy's id, or normalizations and
        strategies joined by ``+`` (``latin-historic+flow``: an unnamed strategy, each strategy its normalizations). With ``use`` (``output`` or ``comparison``), every
        normalization must be meant for it; a named strategy is used as its ``use`` says."""
        ref = entry_id(ref)
        if ref == "literal":
            return ResolvedStrategy("literal", use or "output", ())
        if "+" in ref or ref in self.normalizations:
            parts = tuple(n for x in ref.split("+") for n in (
                [self.normalization(m) for m in self.strategies[x][1].normalizations] if x in self.strategies
                else [self.normalization(x)]))
            kind = use or ("output" if all("output" in n.use for n in parts) else "comparison")
        elif ref in self.strategies:
            doc = self.strategies[ref][1]
            if use is not None and use != doc.use:
                raise CatalogError(f"strategy {ref} is for {doc.use}, not {use}")
            parts, kind = tuple(self.normalization(n) for n in doc.normalizations), doc.use
        else:
            raise CatalogError(f"unknown strategy {ref!r}: 'literal', a strategy ({', '.join(sorted(self.strategies))}) "
                               f"or normalizations joined by '+' ({', '.join(sorted(self.normalizations))})")
        wrong = [n.id for n in parts if kind not in n.use]
        if wrong:
            raise CatalogError(f"strategy {ref}: {wrong} {'is' if len(wrong) == 1 else 'are'} not for {kind}")
        return ResolvedStrategy(ref, kind, parts)

    # -------------------------------------------------------------------------------------------- lookups

    def conventions_doc(self, ref: str) -> ConventionsDoc:
        """The conventions entry ``ref`` (its id; ``id@N`` from before 0.10 resolves with a warning)."""
        cid = entry_id(ref)
        if cid not in self.conventions_entries:
            raise CatalogError(f"unknown conventions {cid!r}; known: {sorted(self.conventions_entries)}")
        return self.conventions_entries[cid][1]

    def conventions(self, ref: str) -> ResolvedConventions:
        """The conventions entry ``ref`` with its chain resolved (``linecaster.markup.resolve``)."""
        try:
            return resolve(entry_id(ref), self.conventions_doc)
        except ConventionsError as e:
            raise CatalogError(str(e)) from None

    @staticmethod
    def conventions_functional(doc: ConventionsDoc) -> dict:
        """A conventions entry's functional content: what its rules do (format, parent, the parent's rules it
        disables, each rule's match, decision, fields, who and place) and the normalizations its transcription
        embodies (stated only), not their documentation."""
        content = {"format": doc.format, "extends": doc.extends, "disable": sorted(doc.disable),
                   "rules": [r.model_dump(mode="json", include={"id", "match", "decision", "params", "by", "before",
                                                                 "after"}, exclude_none=True) for r in doc.rules]}
        if doc.transcription is not None:
            content["transcription"] = list(doc.transcription)
        return content

    def policy(self, ref: str):
        """The rendering policy ``ref`` (its id), as a ``linecaster.data.policy.RenderingPolicy``."""
        pid = entry_id(ref)
        if pid not in self.policies:
            raise CatalogError(f"unknown rendering policy {pid!r}; known: {sorted(self.policies)}")
        return self.policies[pid][1].policy()

    @staticmethod
    def policy_functional(doc: PolicyDoc) -> dict:
        """A policy's functional content: what its YAML states (defaults left out), so that a new optional field
        keeps its hash."""
        return doc.policy().model_dump(mode="json", exclude_defaults=True)

    def model(self, mid: str) -> ModelDoc:
        try:
            return self.models[entry_id(mid)][1]
        except KeyError:
            raise CatalogError(f"unknown model {mid!r}; known: {sorted(self.models)}") from None

    def preset(self, pid: str) -> PresetDoc:
        try:
            return self.presets[entry_id(pid)][1]
        except KeyError:
            raise CatalogError(f"unknown preset {pid!r}; known: {sorted(self.presets)}") from None

    def recipe(self, rid: str) -> RecipeDoc:
        try:
            return self.recipes[entry_id(rid)][1]
        except KeyError:
            raise CatalogError(f"unknown recipe {rid!r}; known: {sorted(self.recipes)}") from None

    def recipe_functional(self, rc: RecipeDoc) -> dict:
        """A recipe's functional content: its pipeline, each slot's preset with its hash (which covers its model
        pin), and the options it states."""
        data = rc.model_dump(mode="json", by_alias=True, include={"pipeline", "options"}, exclude_unset=True)
        data["presets"] = {slot: {"ref": ref, "sha256": self.resolve(ref).sha256}
                           for slot, ref in sorted(rc.presets.items())}
        return data

    def resolve_recipe(self, ref: str, sha256: str | None = None) -> "Resolved":
        """The recipe ``ref`` as this release has it. With ``sha256`` (what a run record names), a different hash
        is a warning: the recipe changed since that run (its record names the linecaster version that ran it)."""
        rid = entry_id(ref)
        if rid not in self.recipes:
            raise CatalogError(f"unknown recipe {rid!r}; known: {sorted(self.recipes)}")
        content = self.recipe_functional(self.recipes[rid][1])
        return Resolved(rid, content, canonical_sha256(content)).checked(sha256)

    def body(self, pid: str) -> str:
        """The Markdown body of preset ``pid`` (the reasons, limitations, changes)."""
        return self.presets[pid][0].bodies["preset"][pid]

    def functional(self, p: PresetDoc) -> dict:
        """The preset's functional content, with the model pin resolved to revision and files."""
        # only what the document states: a new optional schema field must not change a hash
        data = p.model_dump(mode="json", by_alias=True, include=set(FUNCTIONAL), exclude_unset=True)
        if p.model is not None:
            data["model"] = self._pin(p.model)
        if p.submodels:
            data["submodels"] = {role: self._pin(ref) for role, ref in sorted(p.submodels.items())}
        if p.by_script:          # each strategy with its hash, as a recipe names its presets
            data["by_script"] = {code: {"ref": ref, "sha256": self.resolve(ref).sha256}
                                 for code, ref in sorted(p.by_script.items())}
        return data

    def _strategy_problems(self, pid: str, p: PresetDoc) -> list[str]:
        """A by-script preset's strategies: known presets of the same step, each covering its script
        (``linecaster.engines.scripts``) where its engine is installed here."""
        from ..engines import scripts

        out = []
        for code, ref in p.by_script.items():
            try:
                scripts.check_code(code)
                r = self.resolve(ref)
            except (CatalogError, ValueError) as e:
                out.append(f"preset {pid}: by_script {code}: {e.args[0]}")
                continue
            if r.content["step"] != p.step:
                out.append(f"preset {pid}: by_script {code}: {ref} is a {r.content['step']} preset, not {p.step}")
            if r.engine in engine_ids():
                covered = getattr(engine_class(r.engine), "scripts", (scripts.ALL,))
                if not scripts.covers(covered, code):
                    out.append(f"preset {pid}: by_script {code}: {ref} ({r.engine}) covers only {list(covered)}")
        return out

    def _pin(self, ref) -> dict:
        pin = self.model(ref.id).pin(ref.revision)
        return {"id": ref.id, "revision": pin.revision, "files": dict(sorted(pin.files.items()))}

    def resolve(self, ref: str, sha256: str | None = None) -> "Resolved":
        """The preset ``ref`` as this release has it: its functional content and hash. With ``sha256`` (what a run
        record names), a different hash is a warning: the preset changed since that run."""
        pid = entry_id(ref)
        if pid not in self.presets:
            raise CatalogError(f"unknown preset {pid!r}; known: {sorted(self.presets)}")
        content = self.functional(self.presets[pid][1])
        return Resolved(pid, content, canonical_sha256(content)).checked(sha256)

    # ---------------------------------------------------------------------------------------- index, verify

    def recipe_pipeline(self, ref: str) -> dict:
        """The expanded pipeline of recipe ``ref``, built from its pipeline script in this process without
        the engines (``linecaster.runtime.run.describe_recipe``): ``{"pipeline": [...], "pipeline_sha256": ...}``."""
        from ..errors import LinecasterError
        from ..runtime.run import describe_recipe

        try:
            return describe_recipe(ref, self)
        except CatalogError:
            raise
        except LinecasterError as e:
            raise CatalogError(f"recipe {ref}: its pipeline cannot be built: {e}") from e

    def index_data(self, d: Directory, pipelines: bool = True) -> dict:
        """The index of directory ``d``: per kind, each entry's hash; a recipe's also its expanded pipeline's
        (``recipe_pipeline``; with ``pipelines``, needs the pipeline scripts of the checkout)."""
        out: dict[str, dict] = {}
        for kind in KINDS:
            if kind.index_table is None:
                continue
            table = {}
            for eid, doc in sorted(d.entries[kind.name].items()):
                if kind.name == "preset":
                    table[eid] = self.resolve(eid).sha256
                elif kind.name == "recipe":
                    entry = {"sha256": self.resolve_recipe(eid).sha256}
                    if pipelines:
                        entry["pipeline_sha256"] = self.recipe_pipeline(eid)["pipeline_sha256"]
                    table[eid] = entry
                elif kind.name == "policy":
                    table[eid] = canonical_sha256(self.policy_functional(doc))
                elif kind.name == "normalization":
                    table[eid] = self.normalization(eid).sha256
                elif kind.name == "strategy":
                    table[eid] = self.strategy(eid).sha256
                else:
                    table[eid] = canonical_sha256(self.conventions_functional(doc))
            if table:
                out[kind.index_table] = table
        return out

    def write_index(self) -> list[Path]:
        """Writes every directory's ``catalog.index``."""
        return [d.save_index(self.index_data(d)) for d in self.dirs]

    def _index_problems(self, d: Directory, pipelines: bool) -> list[str]:
        """The committed index against the entries: a stale index hides a change of behaviour from review."""
        try:
            fresh = self.index_data(d, pipelines)
        except CatalogError as e:
            return [f"index: {e.args[0]}"]
        committed = d.read_index() or {}
        if not pipelines:
            committed = {t: {k: ({"sha256": v["sha256"]} if isinstance(v, dict) else v) for k, v in rows.items()}
                         for t, rows in committed.items()}
        changed = sorted(f"{t} {k}" for t in set(fresh) | set(committed)
                         for k in set(fresh.get(t, {})) | set(committed.get(t, {}))
                         if fresh.get(t, {}).get(k) != committed.get(t, {}).get(k))
        return [f"{INDEX} is stale ({', '.join(changed[:8])}{' ...' if len(changed) > 8 else ''}): run "
                f"`linecaster catalog index` and name the changed outputs in CHANGELOG.md"] if changed else []

    def _conventions_problems(self, d: Directory) -> list[str]:
        """Conventions entries: resolvable, their decisions applied by their format's importer; across a parent's
        children: a rule all of them repeat (it belongs in the parent), an override equal to what it replaces."""
        from ..formats.html import HtmlConverter

        applied = {"html": HtmlConverter.DECISIONS}
        problems: list[str] = []
        children: dict[str, list[ConventionsDoc]] = {}
        for cid, doc in d.conventions.items():
            try:
                resolved = self.conventions(doc.ref)
            except CatalogError as e:
                problems.append(f"conventions {cid}: {e}")
                continue
            unknown_n = sorted(set(resolved.transcription) - set(self.normalizations))
            if unknown_n:
                problems.append(f"conventions {cid}: transcription names unknown normalizations: {unknown_n}")
            known = applied.get(doc.format)
            if known is not None:
                unknown = sorted({r.decision for r in resolved.rules} - known)
                if unknown:
                    problems.append(f"conventions {cid}: decisions the {doc.format} importer does not apply: "
                                    f"{unknown}")
            if doc.extends:
                pid = doc.extends
                children.setdefault(pid, []).append(doc)
                parent = self.conventions_entries.get(pid)
                if parent is not None:
                    try:
                        inherited = {r.id: r for r in self.conventions(doc.extends).rules}
                    except CatalogError:
                        inherited = {}
                    for r in doc.rules:
                        old = inherited.get(r.id)
                        if old is not None and _function(old) == _function(r) and not (r.before or r.after):
                            problems.append(f"conventions {cid}: rule {r.id} equals the one it replaces in "
                                            f"{doc.extends} (redundant)")
        for pid, kids in children.items():
            if len(kids) < 2:
                continue
            shared = set.intersection(*({json.dumps(_function(r), sort_keys=True) for r in k.rules} for k in kids))
            for f in sorted(shared):
                problems.append(f"conventions {', '.join(sorted(k.id for k in kids))}: rule {json.loads(f)['id']} "
                                f"is the same in every child of {pid}; it belongs in {pid} (promotion)")
        return problems

    def verify(self, files: bool = True, pipelines: bool = True) -> list[str]:
        """Every problem in the catalog, as messages (empty: all good), the committed index included.
        ``pipelines``: build every recipe's pipeline (needs the pipeline scripts of the checkout)."""
        problems = schema_problems()
        for d in self.dirs:
            problems += file_problems(d)
            for mid, m in d.models.items():
                for pin in m.pins:
                    card = d.root / "models" / mid / pin.card
                    if not card.exists():
                        problems.append(f"model {mid}: card {pin.card} is missing")
                    elif files and sha256_file(card) != pin.card_sha256:
                        problems.append(f"model {mid}: card {pin.card} differs from its pinned sha256")
                    if pin.license_file and not (d.root / "models" / mid / pin.license_file).exists():
                        problems.append(f"model {mid}: license file {pin.license_file} is missing")
            for pid, p in d.presets.items():
                bad = []
                for ref in ([p.model] if p.model is not None else []) + list(p.submodels.values()):
                    try:
                        self.model(ref.id).pin(ref.revision)
                    except CatalogError as e:
                        bad.append(f"preset {pid}: {e.args[0]}")
                if bad:
                    problems += bad
                    continue
                if p.superseded_by and entry_id(p.superseded_by) not in self.presets:
                    problems.append(f"preset {pid}: superseded_by {p.superseded_by!r} is unknown")
                strategies = self._strategy_problems(pid, p)
                if strategies:
                    problems += strategies
                    continue
                family = p.engine.split(".")[0]
                known = engine_ids()
                if p.engine not in known and any(k.split(".")[0] == family for k in known):
                    problems.append(f"preset {pid}: engine {p.engine!r} is not registered "
                                    f"({sorted(k for k in known if k.split('.')[0] == family)} are)")
            for rid, rc in d.recipes.items():
                try:
                    self.recipe_functional(rc)
                except CatalogError as e:
                    problems.append(f"recipe {rid}: {e.args[0]}")
                    continue
                if rc.superseded_by and entry_id(rc.superseded_by) not in self.recipes:
                    problems.append(f"recipe {rid}: superseded_by {rc.superseded_by!r} is unknown")
                if pipelines:
                    try:
                        self.recipe_pipeline(rid)
                    except Exception as e:  # noqa: BLE001 - report, do not stop
                        problems.append(f"recipe {rid}: its pipeline cannot be built: {type(e).__name__}: {e}")
            problems += self._conventions_problems(d)
            for sid, doc in d.strategies.items():
                try:
                    self.strategy(sid)
                except CatalogError as e:
                    problems.append(f"strategy {sid}: {e.args[0]}")
            for nid, doc in d.normalizations.items():
                unknown = [x for x in doc.subsumes if x not in self.normalizations]
                if unknown:
                    problems.append(f"normalization {nid}: subsumes unknown normalizations {unknown}")
            if not problems:
                problems += self._index_problems(d, pipelines)
        return problems


def _function(rule) -> dict:
    """What a conventions rule does (not why)."""
    return rule.model_dump(mode="json", include={"id", "match", "decision", "params", "by"}, exclude_none=True)


