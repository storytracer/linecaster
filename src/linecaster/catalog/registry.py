"""Loading, resolving, releasing and verifying the catalog (``docs/reference/catalog.md``).

A catalog directory holds ``models/<id>/model.yaml`` (+ ``upstream/<revision>/``), ``presets/<step>/<id>.yaml``,
``recipes/<id>.yaml``, ``evidence/*.yaml`` and ``catalog.lock``; a model, preset or recipe may have its prose in a
Markdown file next to it (``model.md``, ``<id>.md``), which only the docs read. There is one catalog,
linecaster's own, ``linecaster/catalog/data``: engine packages and derivatives ship none (other directories are
for tests). Engines are found through the entry-point group ``linecaster.engines`` (engine id -> ``module:Class``),
plus linecaster's own (``BUILTIN_ENGINES``).
"""
from __future__ import annotations

import datetime as dt
import hashlib
import json
import os
from dataclasses import dataclass, field
from functools import lru_cache
from importlib import import_module
from importlib.metadata import entry_points
from pathlib import Path
from typing import Any

from . import yamlio
from .schema import SCHEMA_DIR, Evidence, Lock, LockEntry, ModelDoc, PresetDoc, RecipeDoc, json_schemas, schema_file

CORE = Path(__file__).resolve().parent / "data"
LOCK = "catalog.lock"
LOCK_COMMENT = "# generated by `linecaster catalog release`; never edited by hand"
#: the preset fields that can change outputs; everything else is description
FUNCTIONAL = ("step", "model", "submodels", "engine", "options", "settings", "labels", "serve")


def sha256_file(path: str | Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return f"sha256:{h.hexdigest()}"


def canonical_sha256(data: Any) -> str:
    blob = json.dumps(data, sort_keys=True, separators=(",", ":"), ensure_ascii=False, default=str)
    return f"sha256:{hashlib.sha256(blob.encode()).hexdigest()}"


def split_ref(ref: str) -> tuple[str, int | None]:
    """``id@edition`` -> (id, edition); ``id`` -> (id, None)."""
    if "@" in ref:
        pid, ed = ref.rsplit("@", 1)
        return pid, int(ed)
    return ref, None


def modeline(path: str | Path, schema_id: str) -> str:
    """The first line of a catalog file at ``path``: its JSON Schema, relative to the file."""
    rel = os.path.relpath(SCHEMA_DIR / schema_file(schema_id), Path(path).resolve().parent)
    return yamlio.MODELINE.format(Path(rel).as_posix())


def write_entry(path: str | Path, data: dict, prose: str | None = None) -> Path:
    """A catalog entry as ``path`` (YAML, its schema named in the first line) and, with ``prose``, the Markdown
    file next to it (``.md``; removed when ``prose`` is empty)."""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(modeline(path, data["schema"]) + "\n" + yamlio.dump(data), encoding="utf-8")
    if prose is not None:
        md = path.with_suffix(".md")
        if prose.strip():
            md.write_text(prose.strip("\n").rstrip() + "\n", encoding="utf-8")
        else:
            md.unlink(missing_ok=True)
    return path


def _prose(path: Path) -> str:
    md = path.with_suffix(".md")
    return md.read_text(encoding="utf-8") if md.exists() else ""


@dataclass
class Directory:
    """One catalog directory and the entries it holds."""

    root: Path
    models: dict[str, ModelDoc] = field(default_factory=dict)
    model_bodies: dict[str, str] = field(default_factory=dict)
    presets: dict[str, PresetDoc] = field(default_factory=dict)
    preset_bodies: dict[str, str] = field(default_factory=dict)
    recipes: dict[str, RecipeDoc] = field(default_factory=dict)
    recipe_bodies: dict[str, str] = field(default_factory=dict)
    evidence: list[tuple[Path, Evidence]] = field(default_factory=list)
    lock: Lock = field(default_factory=Lock)
    #: every YAML file read, with its schema id
    files: dict[Path, str] = field(default_factory=dict)

    @classmethod
    def load(cls, root: str | Path) -> "Directory":
        d = cls(Path(root))
        for p in sorted(d.root.glob("models/*/model.yaml")):
            m = d._read(ModelDoc, p)
            if m.id != p.parent.name:
                raise ValueError(f"{p}: id {m.id!r} differs from its folder {p.parent.name!r}")
            d.models[m.id], d.model_bodies[m.id] = m, _prose(p)
        for p in sorted(d.root.glob("presets/*/*.yaml")):          # presets/<step>/<id>.yaml
            pr = d._read(PresetDoc, p)
            if pr.id != p.stem:
                raise ValueError(f"{p}: id {pr.id!r} differs from its file name {p.stem!r}")
            if pr.step != p.parent.name:
                raise ValueError(f"{p}: step {pr.step!r} differs from its folder {p.parent.name!r}")
            d.presets[pr.id], d.preset_bodies[pr.id] = pr, _prose(p)
        for p in sorted(d.root.glob("recipes/*.yaml")):
            rc = d._read(RecipeDoc, p)
            if rc.id != p.stem:
                raise ValueError(f"{p}: id {rc.id!r} differs from its file name {p.stem!r}")
            d.recipes[rc.id], d.recipe_bodies[rc.id] = rc, _prose(p)
        for p in sorted(d.root.glob("evidence/*.yaml")):
            d.evidence.append((p, d._read(Evidence, p)))
        lock = d.root / LOCK
        if lock.exists():
            d.lock = d._read(Lock, lock)
        return d

    def _read(self, model, path: Path):
        try:
            data = yamlio.read(path)
        except Exception as e:  # noqa: BLE001 - name the file
            raise ValueError(f"{path}: {e}") from e
        doc = _validate(model, data, path)
        self.files[path] = doc.schema_
        return doc

    def save_lock(self) -> None:
        """Write the lock; an existing file keeps its comments."""
        data = self.lock.model_dump(mode="json", by_alias=True)
        for table in ("presets", "recipes"):
            data[table] = {k: {f: v for f, v in e.items() if not (f == "previous_sha256" and v is None)}
                           for k, e in sorted(data[table].items())}
        if not data["recipes"]:
            data.pop("recipes")
        path = self.root / LOCK
        if path.exists():
            doc = yamlio.read_rt(path)
            text = yamlio.dump_rt(yamlio.update(doc, data))
        else:
            text = f"{modeline(path, data['schema'])}\n{LOCK_COMMENT}\n{yamlio.dump(data)}"
        path.write_text(text, encoding="utf-8")


def _validate(model, data, path):
    try:
        return model.model_validate(data)
    except Exception as e:  # noqa: BLE001 - name the file
        raise ValueError(f"{path}: {e}") from e


class Catalog:
    """The catalog (linecaster's own, ``CORE``); other directories only for tests. Ids are unique."""

    def __init__(self, dirs: list[str | Path] | None = None):
        self.dirs = [Directory.load(d) for d in (dirs if dirs is not None else [CORE])]
        self.models: dict[str, tuple[Directory, ModelDoc]] = {}
        self.presets: dict[str, tuple[Directory, PresetDoc]] = {}
        self.recipes: dict[str, tuple[Directory, RecipeDoc]] = {}
        for d in self.dirs:
            for kind, src, dst in (("model", d.models, self.models), ("preset", d.presets, self.presets),
                                   ("recipe", d.recipes, self.recipes)):
                for k, v in src.items():
                    if k in dst:
                        raise ValueError(f"{kind} {k!r} in both {dst[k][0].root} and {d.root}")
                    dst[k] = (d, v)
        both = set(self.presets) & set(self.recipes)
        if both:
            raise ValueError(f"ids used for a preset and a recipe: {sorted(both)}")

    # -------------------------------------------------------------------------------------------- lookups

    def model(self, mid: str) -> ModelDoc:
        try:
            return self.models[mid][1]
        except KeyError:
            raise KeyError(f"unknown model {mid!r}; known: {sorted(self.models)}") from None

    def preset(self, pid: str) -> PresetDoc:
        try:
            return self.presets[pid][1]
        except KeyError:
            raise KeyError(f"unknown preset {pid!r}; known: {sorted(self.presets)}") from None

    def recipe(self, rid: str) -> RecipeDoc:
        try:
            return self.recipes[rid][1]
        except KeyError:
            raise KeyError(f"unknown recipe {rid!r}; known: {sorted(self.recipes)}") from None

    def recipe_functional(self, rc: RecipeDoc) -> dict:
        """A recipe's functional content: its pipeline, each slot's preset edition with that edition's hash
        (which covers its model pin), and the options it states."""
        data = rc.model_dump(mode="json", by_alias=True, include={"pipeline", "options"}, exclude_unset=True)
        data["presets"] = {slot: {"ref": ref, "sha256": self.resolve(ref).sha256}
                           for slot, ref in sorted(rc.presets.items())}
        return data

    def resolve_recipe(self, ref: str, sha256: str | None = None) -> "Resolved":
        """A recipe edition: the current file when its edition matches, else the lock. With ``sha256``, the hash
        a run record names must be the edition's hash or its hash before a catalog migration."""
        rid, edition = split_ref(ref)
        if rid not in self.recipes:
            raise KeyError(f"unknown recipe {rid!r}; known: {sorted(self.recipes)}")
        d, rc = self.recipes[rid]
        if edition is None or edition == rc.edition:
            content = self.recipe_functional(rc)
            entry = d.lock.recipes.get(rc.ref)
            r = Resolved(rid, rc.edition, content, canonical_sha256(content), released=entry is not None,
                         previous_sha256=entry.previous_sha256 if entry else None)
        else:
            entry = d.lock.recipes.get(f"{rid}@{edition}")
            if entry is None:
                raise KeyError(f"{rid}@{edition} is neither the current edition ({rc.edition}) nor released")
            r = Resolved(rid, edition, entry.resolved, entry.sha256, released=True,
                         previous_sha256=entry.previous_sha256)
        return r.checked(sha256)

    def body(self, pid: str) -> str:
        """The Markdown body of preset ``pid`` (the reasons, limitations, changes)."""
        return self.presets[pid][0].preset_bodies[pid]

    def functional(self, p: PresetDoc) -> dict:
        """The preset's functional content, with the model pin resolved to revision and files."""
        # only what the document states: a new optional schema field must not change released hashes
        data = p.model_dump(mode="json", by_alias=True, include=set(FUNCTIONAL), exclude_unset=True)
        if p.model is not None:
            data["model"] = self._pin(p.model)
        if p.submodels:
            data["submodels"] = {role: self._pin(ref) for role, ref in sorted(p.submodels.items())}
        return data

    def _pin(self, ref) -> dict:
        pin = self.model(ref.id).pin(ref.revision)
        return {"id": ref.id, "revision": pin.revision, "files": dict(sorted(pin.files.items()))}

    def resolve(self, ref: str, sha256: str | None = None) -> "Resolved":
        """A preset edition: the current file when its edition matches (released or draft), else the lock. With
        ``sha256``, the hash a run record names must be the edition's hash or its hash before a catalog
        migration."""
        pid, edition = split_ref(ref)
        d, p = self.presets[pid] if pid in self.presets else (None, None)
        if p is None:
            raise KeyError(f"unknown preset {pid!r}; known: {sorted(self.presets)}")
        if edition is None or edition == p.edition:
            content = self.functional(p)
            entry = d.lock.presets.get(p.ref)
            r = Resolved(pid, p.edition, content, canonical_sha256(content), released=entry is not None,
                         previous_sha256=entry.previous_sha256 if entry else None)
        else:
            entry = d.lock.presets.get(f"{pid}@{edition}")
            if entry is None:
                raise KeyError(f"{pid}@{edition} is neither the current edition ({p.edition}) nor released")
            r = Resolved(pid, edition, entry.resolved, entry.sha256, released=True,
                         previous_sha256=entry.previous_sha256)
        return r.checked(sha256)

    def by_sha256(self, sha256: str) -> "Resolved":
        """The released preset or recipe edition with this hash, today's or the one it had before a catalog
        migration (what an older run record names)."""
        for d in self.dirs:
            for table, resolve in ((d.lock.presets, self.resolve), (d.lock.recipes, self.resolve_recipe)):
                for key, entry in table.items():
                    if sha256 in (entry.sha256, entry.previous_sha256):
                        return resolve(key)
        raise KeyError(f"no released edition has the hash {sha256}")

    # --------------------------------------------------------------------------------------- release, verify

    def release(self, pid: str, commit: str | None = None, today: dt.date | None = None) -> LockEntry:
        """Freeze the current edition of preset or recipe ``pid`` in its catalogue's ``catalog.lock``. A recipe
        is released only on released preset editions."""
        if pid in self.recipes:
            d, doc = self.recipes[pid]
            unreleased = [r for r in doc.presets.values() if not self.resolve(r).released]
            if unreleased:
                raise ValueError(f"recipe {doc.ref}: release its presets first: {unreleased}")
            table, content, kind = d.lock.recipes, self.recipe_functional(doc), "recipe"
        else:
            d, doc = self.presets[pid]
            table, content, kind = d.lock.presets, self.functional(doc), "preset"
        key, sha = doc.ref, canonical_sha256(content)
        old = table.get(key)
        if old is not None:
            if old.sha256 != sha:
                raise ValueError(f"{key} is released with other content; give the {kind} edition {doc.edition + 1}")
            return old
        entry = LockEntry(sha256=sha, released=today or dt.date.today(), linecaster=commit, resolved=content)
        table[key] = entry
        d.save_lock()
        return entry

    def verify(self, files: bool = True) -> list[str]:
        """Every problem in the catalog, as messages (empty: all good)."""
        problems = schema_problems()
        for d in self.dirs:
            problems += file_problems(d)
            for mid, m in d.models.items():
                for pin in m.pins:
                    card = d.root / "models" / mid / pin.card
                    if not card.exists():
                        problems.append(f"model {mid}: card {pin.card} is missing")
                    elif files and sha256_file(card) != pin.card_sha256:
                        problems.append(f"model {mid}: card {pin.card} differs from its pinned sha256")
                    if pin.license_file and not (d.root / "models" / mid / pin.license_file).exists():
                        problems.append(f"model {mid}: licence file {pin.license_file} is missing")
            for pid, p in d.presets.items():
                bad = []
                for ref in ([p.model] if p.model is not None else []) + list(p.submodels.values()):
                    try:
                        self.model(ref.id).pin(ref.revision)
                    except KeyError as e:
                        bad.append(f"preset {pid}: {e.args[0]}")
                if bad:
                    problems += bad
                    continue
                if p.superseded_by and split_ref(p.superseded_by)[0] not in self.presets:
                    problems.append(f"preset {pid}: superseded_by {p.superseded_by!r} is unknown")
                family = p.engine.split(".")[0]
                known = engine_ids()
                if p.engine not in known and any(k.split(".")[0] == family for k in known):
                    problems.append(f"preset {pid}: engine {p.engine!r} is not registered "
                                    f"({sorted(k for k in known if k.split('.')[0] == family)} are)")
                entry = d.lock.presets.get(p.ref)
                if entry is not None and entry.sha256 != canonical_sha256(self.functional(p)):
                    problems.append(f"preset {p.ref} is released, but its functional content changed: "
                                    f"give it edition {p.edition + 1}")
                for key in d.lock.presets:
                    kid, ked = split_ref(key)
                    if kid == pid and ked > p.edition:
                        problems.append(f"preset {pid}: edition {ked} is released but the file is at {p.edition}")
            for rid, rc in d.recipes.items():
                try:
                    content = self.recipe_functional(rc)
                except KeyError as e:
                    problems.append(f"recipe {rid}: {e.args[0]}")
                    continue
                unreleased = [r for r in rc.presets.values() if not self.resolve(r).released]
                if unreleased:
                    problems.append(f"recipe {rid}: preset editions not released: {unreleased}")
                if rc.superseded_by and split_ref(rc.superseded_by)[0] not in self.recipes:
                    problems.append(f"recipe {rid}: superseded_by {rc.superseded_by!r} is unknown")
                entry = d.lock.recipes.get(rc.ref)
                if entry is not None and entry.sha256 != canonical_sha256(content):
                    problems.append(f"recipe {rc.ref} is released, but its functional content changed: "
                                    f"give it edition {rc.edition + 1}")
            for key, entry in [*d.lock.presets.items(), *d.lock.recipes.items()]:
                if canonical_sha256(entry.resolved) != entry.sha256:
                    problems.append(f"lock {key}: its resolved content does not match its sha256")
            for path, ev in d.evidence:
                try:
                    (self.resolve if ev.preset else self.resolve_recipe)(ev.subject)
                except KeyError as e:
                    problems.append(f"evidence {path.name}: {e.args[0]}")
        return problems


#: the support levels whose presets and recipes must explain themselves in a Markdown file
PROSE_REQUIRED = ("core",)


def schema_problems(folder: Path = SCHEMA_DIR) -> list[str]:
    """The committed JSON Schemas against fresh ones from the models."""
    fresh = json_schemas()
    problems = [f"schema {name} differs from the models: run `linecaster catalog schemas`"
                for name, text in fresh.items()
                if not (folder / name).exists() or (folder / name).read_text(encoding="utf-8") != text]
    problems += [f"schema {p.name} belongs to no format" for p in sorted(folder.glob("*.json")) if p.name not in fresh]
    return problems


def file_problems(d: Directory) -> list[str]:
    """The files of a catalog directory: each YAML file names its schema in its first line; Markdown files are
    prose next to a YAML file, without front matter; core presets and recipes have their prose."""
    problems = []
    for path, sid in sorted(d.files.items()):
        want = (SCHEMA_DIR / schema_file(sid)).resolve()
        named = yamlio.modeline(path)
        if named is None:
            problems.append(f"{path.relative_to(d.root)}: the first line does not name its schema "
                            f"({modeline(path, sid)})")
        elif (path.parent / named).resolve() != want:
            problems.append(f"{path.relative_to(d.root)}: names schema {named}, not {schema_file(sid)}")
    for md in sorted([*d.root.glob("presets/*/*.md"), *d.root.glob("recipes/*.md"), *d.root.glob("models/*/*.md")]):
        rel = md.relative_to(d.root)
        if not md.with_suffix(".yaml").exists():
            problems.append(f"{rel}: Markdown without its YAML file ({md.with_suffix('.yaml').name})")
        elif md.read_text(encoding="utf-8").startswith("---\n"):
            problems.append(f"{rel}: front matter in the prose; data belongs in {md.with_suffix('.yaml').name}")
    for f in sorted([*d.root.glob("presets/*/*"), *d.root.glob("recipes/*"), *d.root.glob("evidence/*")]):
        if f.is_file() and f.suffix not in (".yaml", ".md") and f.name != ".gitkeep":
            problems.append(f"{f.relative_to(d.root)}: neither YAML nor Markdown")
    for kind, docs, bodies, folder in (("preset", d.presets, d.preset_bodies, None),
                                       ("recipe", d.recipes, d.recipe_bodies, "recipes")):
        for eid, doc in docs.items():
            if doc.support in PROSE_REQUIRED and not bodies[eid].strip():
                where = f"recipes/{eid}.md" if folder else f"presets/{doc.step}/{eid}.md"
                problems.append(f"{kind} {eid} ({doc.support}): its prose is missing ({where})")
    return problems


@dataclass(frozen=True)
class Resolved:
    """A preset or recipe edition as it runs: id, edition, functional content and its hash."""

    id: str
    edition: int
    content: dict
    sha256: str
    released: bool
    #: its hash before a catalog migration, if that changed it
    previous_sha256: str | None = None

    @property
    def ref(self) -> str:
        return f"{self.id}@{self.edition}"

    def checked(self, sha256: str | None) -> "Resolved":
        """Itself, if ``sha256`` is ``None``, its hash or its previous hash; else a ``ValueError``."""
        if sha256 is not None and sha256 not in (self.sha256, self.previous_sha256):
            raise ValueError(f"{self.ref} has the hash {self.sha256}, not {sha256}")
        return self

    @property
    def engine(self) -> str:
        return self.content["engine"]


@lru_cache(maxsize=1)
def catalog() -> Catalog:
    """The installed catalogue (cached; ``catalog.cache_clear()`` after changing documents)."""
    return Catalog()


